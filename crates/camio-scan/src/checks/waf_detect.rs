/// Detect every WAF/CDN whose fingerprint appears in a response.
pub fn detect(resp: &HttpResponse) -> Vec<&'static str> {
    let mut hits: Vec<&'static str> = Vec::new();
    // Collect all Set-Cookie values once (there can be several).
    let cookies: Vec<&str> = resp.headers.get_all("Set-Cookie").collect();
    let body_lc = if is_html_or_text(resp) {
        resp.body.as_text().to_ascii_lowercase()
    } else {
        String::new()
    };

    for sig in SIGS {
        if sig_matches(sig, resp, &cookies, &body_lc) && !hits.contains(&sig.name) {
            hits.push(sig.name);
        }
    }
    hits
}

fn sig_matches(sig: &WafSig, resp: &HttpResponse, cookies: &[&str], body_lc: &str) -> bool {
    // Header tells.
    for (name, needle) in sig.headers {
        if let Some(val) = resp.headers.get(name) {
            if needle.is_empty() || val.to_ascii_lowercase().contains(&needle.to_ascii_lowercase())
            {
                return true;
            }
        }
    }
    // Cookie tells: Set-Cookie starting with a known name prefix (name is before
    // the first `=`), case-insensitive.
    for raw in cookies {
        let cookie_name = raw.split('=').next().unwrap_or("").trim().to_ascii_lowercase();
        for pfx in sig.cookies {
            if cookie_name.starts_with(&pfx.to_ascii_lowercase()) {
                return true;
            }
        }
    }
    // Body tells (block pages).
    if !body_lc.is_empty() {
        for needle in sig.body {
            if body_lc.contains(&needle.to_ascii_lowercase()) {
                return true;
            }
        }
    }
    false
}

/// Passive WAF/CDN detector.
pub struct WafDetection;

impl PassiveCheck for WafDetection {
    fn id(&self) -> &'static str {
        "waf-detection"
    }

    fn title(&self) -> &'static str {
        "WAF / CDN detected"
    }

    fn severity(&self) -> Severity {
        Severity::Info
    }

    fn check(&self, ex: &HttpExchange) -> Vec<Finding> {
        let Some(resp) = &ex.response else {
            return Vec::new();
        };
        let hits = detect(resp);
        if hits.is_empty() {
            return Vec::new();
        }
        let names = hits.iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", ");
        vec![finding(
            "WAF / CDN detected",
            Severity::Info,
            Confidence::Firm,
            format!(
                "A Web Application Firewall / CDN edge sits in front of this target: {names}. Plan testing accordingly — payloads may be filtered, rate limits tighter, and some responses are the WAF's, not the app's. Detected passively from response headers/cookies/body; no probing packets were sent."
            ),
            ex.id,
        )]
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use camio_core::{Body, HeaderList, HttpRequest, HttpResponse, HttpVersion, Source};

    fn resp_with(headers: &[(&str, &str)], body: &str) -> HttpResponse {
        let mut h = HeaderList::new();
        h.push("Content-Type", "text/html");
        for (k, v) in headers {
            h.push(*k, *v);
        }
        HttpResponse {
            status: 200,
            version: HttpVersion::Http11,
            reason: None,
            headers: h,
            body: Body::from_text(body),
        }
    }

    #[test]
    fn detects_cloudflare_by_header() {
        let r = resp_with(&[("Server", "cloudflare"), ("CF-RAY", "7d1a-DFW")], "<html></html>");
        assert!(detect(&r).contains(&"Cloudflare"));
    }

    #[test]
    fn detects_incapsula_by_cookie() {
        let r = resp_with(&[("Set-Cookie", "incap_ses_123=abc; Path=/")], "<html></html>");
        assert!(detect(&r).contains(&"Imperva Incapsula"));
    }

    #[test]
    fn detects_modsecurity_by_body() {
        let r = resp_with(&[], "<h1>This error was generated by Mod_Security</h1>");
        assert!(detect(&r).contains(&"ModSecurity"));
    }

    #[test]
    fn detects_multiple_stacked_edges() {
        let r = resp_with(
            &[("Server", "cloudflare"), ("X-Sucuri-ID", "08")],
            "<html></html>",
        );
        let hits = detect(&r);
        assert!(hits.contains(&"Cloudflare"));
        assert!(hits.contains(&"Sucuri CloudProxy"));
    }

    #[test]
    fn clean_response_detects_nothing() {
        let r = resp_with(&[("Server", "nginx")], "<html><body>hi</body></html>");
        assert!(detect(&r).is_empty());
    }

    #[test]
    fn check_emits_one_finding_listing_all() {
        let r = resp_with(&[("Server", "cloudflare")], "<html></html>");
        let ex = HttpExchange::new(HttpRequest::get("https://x.test/"), Source::Scanner)
            .with_response(r);
        let f = WafDetection.check(&ex);
        assert_eq!(f.len(), 1);
        assert!(f[0].detail.contains("Cloudflare"));
        assert_eq!(f[0].severity, Severity::Info);
    }
}
