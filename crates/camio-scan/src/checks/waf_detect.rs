//! WAF / CDN detection (inspired by `wafw00f`) — passive attack-surface
//! context (plan §8 "Scan & crawl": automated discovery of what guards a
//! target).
//!
//! Knowing a request passes through a Web Application Firewall or CDN edge
//! changes how an operator tests: payloads may be filtered, rate limits
//! tighter, and some responses are the WAF's, not the app's. This check reads
//! the captured response's headers, cookies and body for the fingerprints each
//! product leaves behind and reports which (if any) is in front of the target.
//! It is **passive** — no probing packets are sent, unlike `wafw00f`'s active
//! mode; it only reads what was already captured.

use crate::checks::{finding, is_html_or_text};
use camio_core::{Confidence, Finding, HttpExchange, HttpResponse, Severity};

use crate::PassiveCheck;

/// One WAF/CDN signature: a product name and the tells it leaves in a response.
/// A match on ANY of `headers` (name or `name: value` substring, case-
/// insensitive), `set_cookie` prefixes, or `body` substrings identifies it.
struct WafSig {
    name: &'static str,
    /// `(header-name, optional value-substring)` pairs. An empty value matches
    /// on the header's mere presence.
    headers: &'static [(&'static str, &'static str)],
    /// `Set-Cookie` name prefixes this product sets.
    cookies: &'static [&'static str],
    /// Distinctive substrings in a block-page body.
    body: &'static [&'static str],
}

